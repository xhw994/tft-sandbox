export function aliasesForUnit(unit, game) {
  if (!unit) return "";
  const parts = [];
  if (UNIT_ALIASES[unit.id]) parts.push(UNIT_ALIASES[unit.id]);
  (unit.traits || []).forEach((tid) => {
    if (TRAIT_ALIASES[tid]) parts.push(TRAIT_ALIASES[tid]);
    const tr = game && game.traitById && game.traitById[tid];
    if (tr && tr.name) parts.push(tr.name);
  });
  return parts.join(" ").toLowerCase();
}

export function aliasesForItem(item) {
  if (!item) return "";
  const parts = [];
  if (ITEM_ALIASES[item.id]) parts.push(ITEM_ALIASES[item.id]);
  if (item.kind === "emblem" && item.trait && TRAIT_ALIASES[item.trait]) {
    parts.push("wz 纹章 转职 " + TRAIT_ALIASES[item.trait]);
  }
  return parts.join(" ").toLowerCase();
}
